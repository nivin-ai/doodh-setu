// Embeds supabase/migrations/*.sql into lib/server/migrations.sql.ts so the server (and Vercel)
// can apply them without reading files at runtime. Runs before every build (npm prebuild).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = 'supabase/migrations';
const files = readdirSync(dir).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(`${dir}/${f}`, 'utf8'))} },`).join('\n');
writeFileSync('lib/server/migrations.sql.ts', `// GENERATED by scripts/bundle-migrations.mjs from supabase/migrations. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`);
console.log(`Bundled ${files.length} migrations`);
